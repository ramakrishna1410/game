using UnityEngine;

namespace MadrasGethu
{
    /// <summary>Builds the player and enemies at runtime (CharacterController + motor + fighter + body).</summary>
    public static class CharacterFactory
    {
        /// <summary>Optional real character models (e.g. Mixamo). Leave null for the placeholder bodies.</summary>
        public static GameObject PlayerModelPrefab;
        public static GameObject EnemyModelPrefab;
        public static GameObject ThadiyanModelPrefab;   // falls back to EnemyModelPrefab
        public static GameObject BossModelPrefab;       // falls back to EnemyModelPrefab
        public static RuntimeAnimatorController FighterAnimator;   // generated by the Setup Characters tool

        /// <summary>Story cast models by lower-case name with no spaces ("selvi", "kutty", "pallu"...).</summary>
        static readonly System.Collections.Generic.Dictionary<string, GameObject> castModels = new System.Collections.Generic.Dictionary<string, GameObject>();

        public static void SetCastModels(GameObject[] models)
        {
            castModels.Clear();
            if (models == null) return;
            foreach (var m in models)
                if (m != null) castModels[Key(m.name)] = m;
        }

        public static GameObject CastModel(string id) => id != null && castModels.TryGetValue(Key(id), out var m) ? m : null;

        static string Key(string s)
        {
            var sb = new System.Text.StringBuilder();
            foreach (char c in s.ToLowerInvariant())
                if (char.IsLetterOrDigit(c)) sb.Append(c);
            return sb.ToString();
        }

        const int IgnoreRaycastLayer = 2;   // the camera's collision check skips fighters

        [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.SubsystemRegistration)]
        static void ResetStatics()
        {
            PlayerModelPrefab = null;
            castModels.Clear();
            EnemyModelPrefab = null;
            ThadiyanModelPrefab = null;
            BossModelPrefab = null;
            FighterAnimator = null;
        }

        static GameObject CreateBody(string name, Vector3 position, float scale)
        {
            var go = new GameObject(name) { layer = IgnoreRaycastLayer };
            go.transform.position = position;

            var cc = go.AddComponent<CharacterController>();
            cc.height = 1.8f * scale;
            cc.radius = 0.35f * scale;
            cc.center = new Vector3(0f, 0.9f * scale, 0f);
            cc.stepOffset = 0.35f;
            cc.slopeLimit = 50f;
            cc.skinWidth = 0.05f;

            go.AddComponent<FighterMotor>();
            return go;
        }

        static FighterVisual AddVisual(GameObject owner, float scale, Color shirt, Color pants, Color accent, GameObject model, bool moustache = true)
        {
            var visualGo = new GameObject("Visual") { layer = IgnoreRaycastLayer };
            visualGo.transform.SetParent(owner.transform, false);
            visualGo.transform.localScale = Vector3.one * scale;
            var visual = visualGo.AddComponent<FighterVisual>();
            visual.shirtColor = shirt;
            visual.pantsColor = pants;
            visual.accentColor = accent;
            visual.hasMoustache = moustache;
            visual.modelPrefab = model;
            visual.fallbackController = FighterAnimator;
            visual.Build();
            return visual;
        }

        public static PlayerFighter CreatePlayer(Vector3 position, ThirdPersonCamera cam)
        {
            var go = CreateBody("Player (Maaran)", position, 1f);
            var player = go.AddComponent<PlayerFighter>();
            go.AddComponent<StoryActor>().castId = "maaran";
            player.ResetHealth(150f);
            player.SetCamera(cam);

            // Black shirt, blue-checked lungi, red towel around the waist: a North Chennai boxer.
            AddVisual(go, 1f,
                new Color(0.08f, 0.08f, 0.1f),
                new Color(0.2f, 0.3f, 0.6f),
                new Color(0.75f, 0.1f, 0.1f),
                PlayerModelPrefab);
            return player;
        }

        /// <summary>
        /// A story character who doesn't fight (Amma, Kutty, Kayal...). Uses their own model (Selvi.fbx...)
        /// if there is one, otherwise the rowdy model, otherwise a placeholder body in their colours.
        /// </summary>
        public static StoryActor CreateNpc(string castId, Vector3 position, Vector3 lookAt)
        {
            var m = Cast.Get(castId);
            var go = CreateBody(m.english, position, m.scale);
            var model = CastModel(castId);
            if (model == null && !m.female) model = EnemyModelPrefab;
            var visual = AddVisual(go, m.scale, m.shirt, m.pants, m.accent, model, m.moustache);
            visual.SetCombatStance(false);
            var actor = go.AddComponent<StoryActor>();
            actor.castId = castId;
            actor.FaceNow(lookAt);
            return actor;
        }

        /// <summary>A named rowdy (Pallu): a normal enemy with his own name, model and colours.</summary>
        public static EnemyFighter CreateNamedEnemy(EnemyKind kind, string castId, Vector3 position)
        {
            var m = Cast.Get(castId);
            var enemy = CreateEnemy(kind, position, CastModel(castId), m);
            enemy.displayName = m.english;
            enemy.gameObject.name = m.english;
            enemy.gameObject.AddComponent<StoryActor>().castId = castId;
            return enemy;
        }

        public static EnemyFighter CreateEnemy(EnemyKind kind, Vector3 position) => CreateEnemy(kind, position, null, null);

        static EnemyFighter CreateEnemy(EnemyKind kind, Vector3 position, GameObject modelOverride, CastMember look)
        {
            var go = CreateBody("Enemy", position, 1f);
            var enemy = go.AddComponent<EnemyFighter>();
            enemy.Configure(kind);
            var profile = enemy.Profile;
            go.name = profile.displayName;

            // Resize the controller for big guys.
            var cc = go.GetComponent<CharacterController>();
            cc.height = 1.8f * profile.scale;
            cc.radius = 0.35f * profile.scale;
            cc.center = new Vector3(0f, 0.9f * profile.scale, 0f);
            enemy.height = 1.8f * profile.scale;

            GameObject model = EnemyModelPrefab;
            if (kind == EnemyKind.Thadiyan && ThadiyanModelPrefab != null) model = ThadiyanModelPrefab;
            if (kind == EnemyKind.Boss && BossModelPrefab != null) model = BossModelPrefab;
            if (modelOverride != null) model = modelOverride;
            if (look != null) AddVisual(go, profile.scale, look.shirt, look.pants, look.accent, model);
            else AddVisual(go, profile.scale, profile.shirt, profile.pants, profile.accent, model);

            var gm = GameManager.Instance;
            if (gm != null && gm.Player != null)
            {
                Vector3 toPlayer = Vector3.ProjectOnPlane(gm.Player.transform.position - position, Vector3.up);
                if (toPlayer.sqrMagnitude > 0.01f) go.transform.rotation = Quaternion.LookRotation(toPlayer);
            }
            return enemy;
        }
    }
}
